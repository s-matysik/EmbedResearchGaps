def signature_of(obj: object) -> str:
    try:
        return str(inspect.signature(obj))  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return ""


def render_entry(module: str, name: str, obj: object) -> str:
    anchor = slug(f"{module}-{name}")
    doc = inspect.getdoc(obj) or ""
    if inspect.isclass(obj):
        kind = "class"
    elif inspect.isfunction(obj) or inspect.isbuiltin(obj):
        kind = "function"
    else:
        kind = "constant"

    parts = [f'<section class="entry" id="{anchor}">']
    signature = html.escape(signature_of(obj), quote=False) if kind != "constant" else ""
    parts.append(
        f'<h3><span class="kind">{kind}</span> <code class="sym">{name}</code>'
        f'<code class="sig">{signature}</code>'
        f'<a class="anchor" href="#{anchor}">#</a></h3>'
    )
    if kind == "constant":
        parts.append(f"<pre><code>{html.escape(repr(obj)[:600], quote=False)}</code></pre>")
    parts.append(render_docstring(doc))

    fields = getattr(obj, "__dataclass_fields__", None) if inspect.isclass(obj) else None
    if fields:
        rows = []
        for field in fields.values():
            default = (
                "" if field.default is dataclasses.MISSING
                else html.escape(repr(field.default), quote=False)
            )
            if not default and field.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                default = "<em>factory</em>"
            rows.append(
                f"<tr><td><code>{html.escape(field.name)}</code></td>"
                f"<td><code>{html.escape(str(field.type), quote=False)}</code></td>"
                f"<td><code>{default}</code></td></tr>"
            )
        parts.append(
            '<p class="doc-section">Fields</p><table class="fields"><thead><tr>'
            "<th>Name</th><th>Type</th><th>Default</th></tr></thead><tbody>"
            + "".join(rows)
            + "</tbody></table>"
        )

    if inspect.isclass(obj):
        methods = []
        for mname, member in inspect.getmembers(obj):
            if mname.startswith("_"):
                continue
            if isinstance(member, property):
                methods.append((mname, "", inspect.getdoc(member.fget) or ""))
            elif inspect.isfunction(member):
                methods.append((mname, signature_of(member), inspect.getdoc(member) or ""))
        if methods:
            parts.append('<p class="doc-section">Methods</p><dl class="methods">')
            for mname, msig, mdoc in methods:
                summary = mdoc.strip().splitlines()[0] if mdoc.strip() else ""
                parts.append(
                    f"<dt><code>{html.escape(mname)}"
                    f"{html.escape(msig, quote=False)}</code></dt>"
                    f"<dd>{inline(summary)}</dd>"
                )
            parts.append("</dl>")
    parts.append("</section>")
    return "\n".join(parts)


