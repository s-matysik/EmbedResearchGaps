# --------------------------------------------------------------------------
# A markdown subset: headings, fenced code, tables, lists, quotes, inline spans.
# --------------------------------------------------------------------------

_INLINE_CODE = re.compile(r"`([^`]+)`")
_BOLD = re.compile(r"\*\*([^*]+)\*\*")
_ITALIC = re.compile(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])")
_LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")


def inline(text: str) -> str:
    """Escape, then re-introduce the inline spans markdown defines."""
    out = html.escape(text, quote=False)
    placeholders: list[str] = []

    def stash(match: re.Match[str]) -> str:
        placeholders.append(f"<code>{match.group(1)}</code>")
        return f"\x00{len(placeholders) - 1}\x00"

    out = _INLINE_CODE.sub(stash, out)
    out = _LINK.sub(r'<a href="\2">\1</a>', out)
    out = _BOLD.sub(r"<strong>\1</strong>", out)
    out = _ITALIC.sub(r"<em>\1</em>", out)
    for index, value in enumerate(placeholders):
        out = out.replace(f"\x00{index}\x00", value)
    return out


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def markdown(source: str, heading_offset: int = 0) -> str:
    """Render the markdown subset this project's documents actually use."""
    lines = source.splitlines()
    out: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]

        if line.startswith("```"):
            language = line[3:].strip()
            body: list[str] = []
            index += 1
            while index < len(lines) and not lines[index].startswith("```"):
                body.append(lines[index])
                index += 1
            index += 1
            klass = f' class="lang-{html.escape(language)}"' if language else ""
            out.append(
                f"<pre{klass}><code>"
                + html.escape("\n".join(body), quote=False)
                + "</code></pre>"
            )
            continue

        if line.startswith("#"):
            level = len(line) - len(line.lstrip("#"))
            text = line[level:].strip()
            level = min(level + heading_offset, 6)
            anchor = slug(text)
            out.append(
                f'<h{level} id="{anchor}">{inline(text)}'
                f'<a class="anchor" href="#{anchor}">#</a></h{level}>'
            )
            index += 1
            continue

        if line.lstrip().startswith("|") and index + 1 < len(lines) and re.fullmatch(
            r"\s*\|[\s:|-]+\|\s*", lines[index + 1]
        ):
            header = [c.strip() for c in line.strip().strip("|").split("|")]
            index += 2
            rows: list[list[str]] = []
            while index < len(lines) and lines[index].lstrip().startswith("|"):
                rows.append([c.strip() for c in lines[index].strip().strip("|").split("|")])
                index += 1
            head = "".join(f"<th>{inline(c)}</th>" for c in header)
            body = "".join(
                "<tr>" + "".join(f"<td>{inline(c)}</td>" for c in row) + "</tr>"
                for row in rows
            )
            out.append(f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>")
            continue

        bullet = re.match(r"\s*([-*]|\d+\.)\s+", line)
        if bullet:
            ordered = bullet.group(1).endswith(".")
            items: list[str] = []
            while index < len(lines):
                match = re.match(r"\s*(?:[-*]|\d+\.)\s+(.*)", lines[index])
                if not match:
                    if lines[index].startswith(("  ", "\t")) and items:
                        items[-1] += " " + lines[index].strip()
                        index += 1
                        continue
                    break
                items.append(match.group(1))
                index += 1
            tag = "ol" if ordered else "ul"
            out.append(
                f"<{tag}>" + "".join(f"<li>{inline(i)}</li>" for i in items) + f"</{tag}>"
            )
            continue

        if line.startswith(">"):
            quote: list[str] = []
            while index < len(lines) and lines[index].startswith(">"):
                quote.append(lines[index].lstrip(">").strip())
                index += 1
            out.append(f"<blockquote>{inline(' '.join(quote))}</blockquote>")
            continue

        if not line.strip():
            index += 1
            continue

        paragraph: list[str] = []
        while (
            index < len(lines)
            and lines[index].strip()
            and not lines[index].startswith(("#", "```", ">", "|"))
            and not re.match(r"\s*(?:[-*]|\d+\.)\s+", lines[index])
        ):
            paragraph.append(lines[index].strip())
            index += 1
        out.append(f"<p>{inline(' '.join(paragraph))}</p>")
    return "\n".join(out)


# --------------------------------------------------------------------------
# numpydoc docstrings
# --------------------------------------------------------------------------

_SECTIONS = ("Parameters", "Returns", "Raises", "Yields", "Notes", "Examples",
             "Attributes", "See Also", "References", "Warnings")


def render_docstring(text: str) -> str:
    """Render a numpydoc docstring: prose, parameter lists, example blocks."""
    if not text:
        return ""
    lines = text.splitlines()
    blocks: list[tuple[str, list[str]]] = [("", [])]
    index = 0
    while index < len(lines):
        line = lines[index]
        if (
            line.strip() in _SECTIONS
            and index + 1 < len(lines)
            and set(lines[index + 1].strip()) == {"-"}
        ):
            blocks.append((line.strip(), []))
            index += 2
            continue
        blocks[-1][1].append(line)
        index += 1

    out: list[str] = []
    for title, body in blocks:
        content = "\n".join(body).strip("\n")
        if not content.strip():
            continue
        if title in {"Examples", "Notes", "References", "See Also", "Warnings"}:
            out.append(f'<p class="doc-section">{title}</p>')
            if title == "Examples":
                out.append(f"<pre><code>{html.escape(content, quote=False)}</code></pre>")
            else:
                out.append(markdown(inspect.cleandoc(content), heading_offset=3))
            continue
        if title in {"Parameters", "Returns", "Raises", "Yields", "Attributes"}:
            out.append(f'<p class="doc-section">{title}</p><dl class="params">')
            name: str | None = None
            description: list[str] = []
            for raw in content.splitlines():
                if raw.strip() and not raw.startswith((" ", "\t")):
                    if name is not None:
                        out.append(
                            f"<dt>{inline(name)}</dt><dd>{inline(' '.join(description))}</dd>"
                        )
                    name, description = raw.strip(), []
                elif raw.strip():
                    description.append(raw.strip())
            if name is not None:
                out.append(f"<dt>{inline(name)}</dt><dd>{inline(' '.join(description))}</dd>")
            out.append("</dl>")
            continue
        out.append(markdown(content, heading_offset=3))
    return "\n".join(out)


